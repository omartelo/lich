// Lobe returns the Lobe mark of that name, drawn filled. It panics on a name
// the set does not have, like Lucide.
func Lobe(name string) *Icon {
	d, ok := lobePaths[name]
	if !ok {
		panic(fmt.Sprintf("icons: no Lobe icon %q", name))
	}
	ic, err := fillOnly(d)
	if err != nil {
		panic(fmt.Sprintf("icons: Lobe %q: %v", name, err))
	}
	return ic
}
